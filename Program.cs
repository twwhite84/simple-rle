// compresses into [tile_id, count] with 1 byte for id, 2 bytes for count
static uint[] Squish(uint[] unsquished_map)
{
    List<uint> ids = [];
    List<uint> counts = [];

    ids.Add(unsquished_map[0]);
    uint count = 1;
    for (uint i = 1; i < unsquished_map.Length; i++)
    {
        if (unsquished_map[i] != unsquished_map[i - 1])
        {
            counts.Add(count);
            ids.Add(unsquished_map[i]);
            count = 1;
        }
        else
        {
            count++;
        }
    }
    counts.Add(count);

    uint[] combined = new uint[ids.Count];
    for (int i = 0; i < ids.Count; i++)
    {
        uint combined_id = ids[i] << 16;
        uint combined_count = counts[i];
        combined[i] = combined_id | combined_count;
        Console.WriteLine(combined[i].ToString("X6"));
    }

    int bytes_required = combined.Length * 3;
    Console.WriteLine($"uncompressed: {unsquished_map.Length} bytes");
    Console.WriteLine($"compressed: {bytes_required} bytes");
    Console.WriteLine($"ratio: {MathF.Round((float)unsquished_map.Length / (float)bytes_required, 2)}x");
    return combined;
}

static List<uint> Unsquish(uint[] squished_map)
{
    List<uint> unsquished = [];
    foreach (uint combined in squished_map)
    {
        uint id = combined >> 16;
        uint count = combined & 0xffff;
        for (int i = 0; i < count; i++)
        {
            unsquished.Add(id);
        }
    }
    return unsquished;
}

